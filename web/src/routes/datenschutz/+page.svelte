<div class="card text">
	<h1>Datenschutz</h1>
	<p>
		Die Familien-Kommandozentrale ist eine private, selbst gehostete Anwendung für die Mitglieder
		eines Haushalts. Sie ist nicht öffentlich nutzbar.
	</p>
	<h2>Welche Daten verarbeitet werden</h2>
	<ul>
		<li>Namen, Farben, Fotos und PINs (nur als Hash) der Familienmitglieder</li>
		<li>
			Kalendertermine aus den verbundenen Google-Konten (Titel, Zeit, Ort, Beschreibung), um sie
			anzuzeigen und auf Wunsch zu ändern
		</li>
		<li>Die Liste der Google-Kalender eines verbundenen Kontos</li>
	</ul>
	<h2>Wo die Daten liegen</h2>
	<p>
		Alle Daten liegen ausschließlich auf dem eigenen Server des Haushalts. Google-Zugangsdaten
		werden verschlüsselt gespeichert. Es gibt keine Weitergabe an Dritte, keine Werbung und keine
		Analyse.
	</p>
	<h2>Google-Zugriff beenden</h2>
	<p>
		Die Verbindung lässt sich jederzeit unter Einstellungen → Kalender trennen oder unter
		<a href="https://myaccount.google.com/permissions" rel="noreferrer"
			>myaccount.google.com/permissions</a
		>
		widerrufen.
	</p>
</div>

